BLOCK_START = "<!-- historical-layers:start (generated by vap.episode build) -->"
BLOCK_END = "<!-- historical-layers:end -->"
SOURCE_TAGS = ("source:name", "attribution", "source:geometry", "source", "source:url")


def source_key(tags: dict) -> str | None:
    """Which known source a CC BY way comes from; None means a person must look at it."""
    text = " ".join(str(tags.get(key, "")) for key in SOURCE_TAGS)
    for key, (pattern, _, _) in SOURCES.items():
        if re.search(pattern, text, re.IGNORECASE):
            return key
    return None


def short_credit(base: str, keys) -> str:
    extra = [SOURCES[key][2] for key in sorted(keys) if key in SOURCES and SOURCES[key][2]]
    return " · ".join([base, *extra])


def full_texts(keys) -> list[str]:
    return [SOURCES[key][1] for key in sorted(keys) if key in SOURCES]


def render(slug: str, credit: str, lines: list[str], unmapped: list[dict]) -> str:
    out = [f"# Attribution: {slug}", "", f"On screen: {credit}", "", "Video description:", ""]
    out += [f"- {line}" for line in lines]
    if unmapped:
        out += ["", "## Needs review: CC BY ways from an unknown source", ""]
        out += [f"- {row['id']}: {row['source']}" for row in unmapped]
    return "\n".join(out) + "\n"


def write(target: Path, slug: str, credit: str, lines: list[str], unmapped=()) -> None:
    path = target.with_suffix(".attribution.md")
    path.write_text(render(slug, credit, lines, list(unmapped)), encoding="utf-8", newline="\n")


def update_episode(target: Path, root: Path, story: dict) -> None:
    """Keep the historical layers' attribution in the episode's attributions.md.

    Only the marked block changes, so hand-written credits stay as they are.
    """
    from .errata import used_layers

    sections = []
    for plate, slug in dict.fromkeys(
        (plate, layer["props"]["slug"]) for _, layer, plate in used_layers(story)
    ):
        path = root / "data/processed" / plate / "historical" / f"{slug}.attribution.md"
        sections.append(path.read_text(encoding="utf-8").strip())
    text = target.read_text(encoding="utf-8") if target.is_file() else ""
    pattern = re.compile(f"{re.escape(BLOCK_START)}.*?{re.escape(BLOCK_END)}\\n?", re.DOTALL)
    kept = pattern.sub("", text).rstrip()
    if sections:
        block = "\n\n".join([BLOCK_START, *sections, BLOCK_END]) + "\n"
        kept = f"{kept}\n\n{block}" if kept else block
    elif kept:
        kept += "\n"
    if kept != text:
        target.write_text(kept, encoding="utf-8", newline="\n")
